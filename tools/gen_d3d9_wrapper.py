"""Generate a forwarding IDirect3DDevice9 wrapper from the Windows SDK's d3d9.h.

The output (build/rt_device_gen.h) defines RtDeviceGen, a class implementing every
IDirect3DDevice9 method except IUnknown's. Each method forwards through
TSCFIX_RT_FORWARD(slot, Name, Ret, (args...)), which proxy/rtdevice.h defines; this
keeps policy (direct call, queue, synchronous call) out of the generated code.

Generated at build time and never committed (it is derived from the SDK header).

    python -I tools/gen_d3d9_wrapper.py <path to d3d9.h> <output .h>
"""
import re
import sys


def split_params(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
            continue
        depth += ch == "("
        depth -= ch == ")"
        cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def name_params(params):
    """Return (declarations, names); unnamed parameters (a few exist in d3d9.h) get a{i}."""
    decls, names = [], []
    for i, p in enumerate(params):
        idents = [t for t in re.findall(r"[A-Za-z_]\w*", p) if t not in ("CONST", "const")]
        if p.rstrip().endswith("*") or len(idents) == 1:
            p = f"{p} a{i}"
        decls.append(p)
        names.append(re.search(r"([A-Za-z_]\w*)\s*(\[[^\]]*\])?\s*$", p).group(1))
    return decls, names


def main(header, out_path):
    text = open(header, encoding="utf-8", errors="replace").read()
    start = text.index("DECLARE_INTERFACE_(IDirect3DDevice9, IUnknown)")
    end = text.index("#ifdef D3D_DEBUG_INFO", start)
    body = text[start:end]
    methods = []
    for m in re.finditer(r"STDMETHOD(?:_\(\s*([^,]+?)\s*,\s*(\w+)\)|\((\w+)\))\s*\(THIS_?\s*([^)]*(?:\([^)]*\)[^)]*)*)\)\s*PURE;", body):
        ret = (m.group(1) or "HRESULT").strip()
        name = m.group(2) or m.group(3)
        params = split_params(m.group(4).strip())
        methods.append((ret, name, params))
    assert len(methods) == 119, f"expected 119 methods, parsed {len(methods)}"

    lines = [
        "// Generated by tools/gen_d3d9_wrapper.py from the Windows SDK d3d9.h. Do not edit or commit.",
        "#pragma once",
        "#include <d3d9.h>",
        "",
        "class RtDeviceGen : public IDirect3DDevice9 {",
        " protected:",
        "    IDirect3DDevice9* real_ = nullptr;  // the runtime's device",
        "    // Runs before every call that goes straight to the runtime (slot = vtable index).",
        "    virtual void BeforeSync(int /*slot*/) {}",
        "",
        " public:",
        "    virtual ~RtDeviceGen() = default;",
    ]
    for slot, (ret, name, params) in enumerate(methods):
        if slot < 3:  # IUnknown is written by hand
            continue
        decls, names = name_params(params)
        decl = ", ".join(decls)
        args = ", ".join(names)
        lines.append(f"    {ret} STDMETHODCALLTYPE {name}({decl}) override {{")
        lines.append(f"        TSCFIX_RT_FORWARD({slot}, {name}, {ret}, ({args}));")
        lines.append("    }")
    lines.append("};")
    lines.append("")
    lines.append("inline const char* const kRtDeviceMethodNames[] = {")
    lines.append("    " + ", ".join(f'"{n}"' for _, n, _ in methods))
    lines.append("};")
    open(out_path, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"generated {len(methods)} methods -> {out_path}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
